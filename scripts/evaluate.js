import { mkdir, writeFile } from "node:fs/promises";
import { performance } from "node:perf_hooks";
import { compare, lineDiff, ENGINE_VERSION } from "../src/engine.js";
import { demo } from "../src/demo.js";
import { fixtures } from "../tests/fixtures.js";
const rows = fixtures.map((f) => {
  const started = performance.now();
  const actual = compare(f.before, f.after, f.procedure).results[0].category;
  const ms = performance.now() - started;
  const diff = lineDiff(f.before, f.after);
  return {
    name: f.name,
    expected: f.expected,
    actual,
    matches: actual === f.expected,
    knownLimitation: f.knownLimitation || null,
    changedDiffLines: diff.lines.filter((l) => l.kind !== "same").length,
    elapsedMs: Number(ms.toFixed(3)),
  };
});
const d = lineDiff(demo.before, demo.after),
  r = compare(demo.before, demo.after, demo.procedure);
const demoStats = {
  rawAddedLines: d.lines.filter((l) => l.kind === "add").length,
  rawRemovedLines: d.lines.filter((l) => l.kind === "remove").length,
  procedureSteps: r.results.length,
  categories: r.counts,
};
const unexpected = rows.filter((r) => !r.matches && !r.knownLimitation);
const md = `# Diagnostic evaluation\n\nGenerated by \`npm run evaluate\` using engine ${ENGINE_VERSION}. All cases are synthetic and hand-authored during development, not a held-out benchmark.\n\n${rows.filter((r) => r.matches).length}/${rows.length} routing expectations matched. ${rows.filter((r) => !r.matches).length} known limitations remain. This is not a real-world accuracy estimate or evidence of superiority over text diff.\n\n| Case | Desired routing | Actual routing | Raw changed lines | Outcome |\n|---|---|---|---:|---|\n${rows.map((r) => `| ${r.name} | ${r.expected} | ${r.actual} | ${r.changedDiffLines} | ${r.matches ? "Matches expectation" : "KNOWN MISS"} |`).join("\n")}\n\n## Baseline on the demonstration\n\nThe simple line diff produces ${demoStats.rawAddedLines} added and ${demoStats.rawRemovedLines} removed lines. This includes title, brand copy, a removed section and changed example wording. What Changed? presents ${demoStats.procedureSteps} procedure steps: ${r.counts.changed} review change, ${r.counts.unchanged} text unchanged, ${r.counts.uncertain} uncertain. The diff and step labels measure different things; no numerical accuracy or time-saving comparison is justified. Raw diff remains available because it exposes changes outside the checklist.\n\n## Known failures retained in the evaluation\n\n${rows
  .filter((r) => !r.matches)
  .map(
    (r) =>
      `- **${r.name}:** ${r.knownLimitation} Desired ${r.expected}; actual ${r.actual}.`,
  )
  .join(
    "\n",
  )}\n\n## Performance scope\n\nDiagnostic cases execute locally in Node. Measured elapsed times are in evaluation.json and vary by hardware/process. These small fixtures do not establish worst-case latency, memory, or usability. No model, network request, key or paid service is involved.\n`;
await mkdir("docs", { recursive: true });
await writeFile("docs/evaluation.md", md);
await writeFile(
  "docs/evaluation.json",
  JSON.stringify(
    {
      engineVersion: ENGINE_VERSION,
      runtime: process.version,
      platform: `${process.platform}/${process.arch}`,
      rows,
      demo: demoStats,
      unexpectedFailures: unexpected.length,
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `${rows.filter((r) => r.matches).length}/${rows.length} diagnostic expectations matched; ${rows.filter((r) => !r.matches && r.knownLimitation).length} documented misses; ${unexpected.length} unexpected failures.`,
);
if (unexpected.length) process.exitCode = 1;
